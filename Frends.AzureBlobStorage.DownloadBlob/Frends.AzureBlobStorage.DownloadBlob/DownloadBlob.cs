using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using System.ComponentModel;
using Frends.AzureBlobStorage.DownloadBlob.Definitions;
using Frends.AzureBlobStorage.DownloadBlob.Helpers;

namespace Frends.AzureBlobStorage.DownloadBlob;

/// <summary>
/// Azure Blob Storage task.
/// </summary>
public static class AzureBlobStorage
{
    /// <summary>
    /// Downloads a Blob from Azure Blob Storage to the local file system.
    /// [Documentation](https://tasks.frends.com/tasks/frends-tasks/Frends.AzureBlobStorage.DownloadBlob)
    /// </summary>
    /// <param name="input">Specifies which blob to download and where to save it.</param>
    /// <param name="options">Encoding and error-handling settings.</param>
    /// <param name="connection">Azure Blob Storage connection parameters.</param>
    /// <param name="cancellationToken">Token generated by Frends to stop this task.</param>
    /// <returns>Object { bool Success, string FilePath, Error Error }</returns>
    public static async Task<Result> DownloadBlob([PropertyTab] Input input, [PropertyTab] Options options,
        [PropertyTab] Connection connection,
        CancellationToken cancellationToken)
    {
        try
        {
            ValidationHandler.Run(input, connection);
            var blob = ConnectionHandler.GetBlobClient(connection, input.ContainerName, input.BlobName,
                cancellationToken);
            var blobFileName = string.IsNullOrWhiteSpace(input.TargetFileName)
                ? input.BlobName
                : input.TargetFileName;
            var fullDestinationPath = Path.Combine(input.TargetDirectory, blobFileName);
            var fileName = blobFileName.Split('.')[0];
            var fileExtension = "";

            if (blobFileName.Split('.').Length > 1)
            {
                fileName = string.Join(".", blobFileName.Split('.').Take(blobFileName.Split('.').Length - 1).ToArray());
                fileExtension = "." + blobFileName.Split('.').Last();
            }

            if (input.ActionOnExistingFile == FileExistsAction.Throw && File.Exists(fullDestinationPath))
                throw new IOException(
                    "File already exists in destination path. Please delete the existing file or change the \"ActionOnExistingFile\" to Overwrite.");

            if (input.ActionOnExistingFile == FileExistsAction.Rename && File.Exists(fullDestinationPath))
            {
                var increment = 1;
                var incrementedFileName = $"{fileName}({increment}){fileExtension}";

                while (File.Exists(Path.Combine(input.TargetDirectory, incrementedFileName)))
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    increment++;
                    incrementedFileName = $"{fileName}({increment}){fileExtension}";
                }

                fullDestinationPath = Path.Combine(input.TargetDirectory, incrementedFileName);
                blobFileName = incrementedFileName;
                await blob.DownloadToAsync(fullDestinationPath, cancellationToken);
            }
            else
            {
                await blob.DownloadToAsync(fullDestinationPath, cancellationToken);
            }

            var encoding = GetEncoding(options.Encoding, options.OtherEncoding);
            CheckAndFixFileEncoding(fullDestinationPath, input.TargetDirectory, fileExtension, encoding);

            return new Result { Success = true, FilePath = fullDestinationPath, Error = null };
        }
        catch (Exception ex)
        {
            return ErrorHandler.Handle(ex, options.ThrowErrorOnFailure, options.ErrorMessageOnFailure);
        }
    }

    private static void CheckAndFixFileEncoding(string fullPath, string directory, string fileExtension,
        Encoding targetEncoding)
    {
        string encoding;

        using (var reader = new StreamReader(fullPath, true))
        {
            reader.Read();
            encoding = reader.CurrentEncoding.BodyName;
        }

        if (targetEncoding.BodyName != encoding)
        {
            var tempFilePath = Path.Combine(directory, "encodingTemp" + fileExtension);

            using (var sr = new StreamReader(fullPath, true))
            using (var sw = new StreamWriter(tempFilePath, false, targetEncoding))
            {
                var line = string.Empty;
                while ((line = sr.ReadLine()) != null)
                    sw.WriteLine(line);
            }

            File.Delete(fullPath);
            File.Copy(tempFilePath, fullPath);
            File.Delete(tempFilePath);
        }
    }

    private static Encoding GetEncoding(FileEncoding encoding, string encodingString)
    {
        switch (encoding)
        {
            case FileEncoding.UTF8WithBOM:
                return new UTF8Encoding(true);
            case FileEncoding.UTF8:
                return new UTF8Encoding(false);
            case FileEncoding.ASCII:
                return new ASCIIEncoding();
            case FileEncoding.Default:
                return Encoding.Default;
            case FileEncoding.Windows1252:
                return CodePagesEncodingProvider.Instance.GetEncoding("windows-1252");
            case FileEncoding.Other:
                try
                {
                    var encodingFromString = CodePagesEncodingProvider.Instance.GetEncoding(encodingString);

                    if (encodingFromString == null)
                        throw new ArgumentException($"Encoding '{encodingString}' is not supported.");

                    return encodingFromString;
                }
                catch (ArgumentException ex)
                {
                    throw new ArgumentException($"Invalid encoding string '{encodingString}': {ex.Message}");
                }
            default:
                throw new ArgumentOutOfRangeException($"Unknown Encoding type: '{encoding}'.");
        }
    }
}
